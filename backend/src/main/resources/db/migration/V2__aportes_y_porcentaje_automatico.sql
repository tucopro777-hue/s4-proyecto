-- Porcentaje de cada ingreso que se aporta automáticamente a la meta. NULL = desactivado.
ALTER TABLE metas_ahorro ADD COLUMN porcentaje_automatico NUMERIC(5,2);
ALTER TABLE metas_ahorro ADD CONSTRAINT ck_meta_porcentaje
    CHECK (porcentaje_automatico IS NULL OR (porcentaje_automatico > 0 AND porcentaje_automatico <= 100));

-- Historial de aportes a metas. Cada aporte sale de una billetera; si viene de un ingreso,
-- queda vinculado a esa transacción para poder revertirlo al anularla.
CREATE TABLE aportes_meta (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id      BIGINT        NOT NULL REFERENCES usuarios (id),
    meta_id         BIGINT        NOT NULL REFERENCES metas_ahorro (id),
    billetera_id    BIGINT        NOT NULL REFERENCES billeteras (id),
    transaccion_id  BIGINT                 REFERENCES transacciones (id),
    monto           NUMERIC(12,2) NOT NULL,
    fecha           DATE          NOT NULL,
    automatico      BOOLEAN       NOT NULL,
    CONSTRAINT ck_aporte_monto_positivo CHECK (monto > 0)
);
