-- Esquema inicial del sistema de finanzas personales.
-- Debe coincidir con las entidades JPA: Hibernate lo valida al arrancar (ddl-auto=validate).

CREATE TABLE usuarios (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre          VARCHAR(100)  NOT NULL,
    email           VARCHAR(150)  NOT NULL,
    password        VARCHAR(255)  NOT NULL,
    fecha_registro  TIMESTAMP     NOT NULL,
    CONSTRAINT uk_usuarios_email UNIQUE (email)
);

CREATE TABLE billeteras (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre         VARCHAR(100)  NOT NULL,
    saldo_inicial  NUMERIC(12,2) NOT NULL,
    saldo_actual   NUMERIC(12,2) NOT NULL,
    divisa         VARCHAR(3)    NOT NULL,
    activa         BOOLEAN       NOT NULL,
    usuario_id     BIGINT        NOT NULL REFERENCES usuarios (id)
);

CREATE TABLE categorias (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre      VARCHAR(50)  NOT NULL,
    tipo        VARCHAR(20)  NOT NULL,
    color       VARCHAR(7)   NOT NULL,
    icono       VARCHAR(30)  NOT NULL,
    activa      BOOLEAN      NOT NULL,
    usuario_id  BIGINT       NOT NULL REFERENCES usuarios (id),
    CONSTRAINT uk_categoria_usuario_nombre UNIQUE (usuario_id, nombre)
);

CREATE TABLE transacciones (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    monto         NUMERIC(12,2) NOT NULL,
    tipo          VARCHAR(20)   NOT NULL,
    descripcion   VARCHAR(255),
    fecha         DATE          NOT NULL,
    anulada       BOOLEAN       NOT NULL,
    usuario_id    BIGINT        NOT NULL REFERENCES usuarios (id),
    billetera_id  BIGINT        NOT NULL REFERENCES billeteras (id),
    categoria_id  BIGINT        NOT NULL REFERENCES categorias (id)
);

CREATE TABLE presupuestos (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id       BIGINT        NOT NULL REFERENCES usuarios (id),
    categoria_id     BIGINT        NOT NULL REFERENCES categorias (id),
    monto_limite     NUMERIC(12,2) NOT NULL,
    anio             INTEGER       NOT NULL,
    mes              INTEGER       NOT NULL,
    saldo_consumido  NUMERIC(12,2) NOT NULL,
    CONSTRAINT uk_presupuesto_periodo UNIQUE (usuario_id, categoria_id, anio, mes)
);

CREATE TABLE metas_ahorro (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id     BIGINT        NOT NULL REFERENCES usuarios (id),
    nombre         VARCHAR(100)  NOT NULL,
    monto_objetivo NUMERIC(12,2) NOT NULL,
    monto_actual   NUMERIC(12,2) NOT NULL,
    fecha_limite   DATE
);

-- Traspasos entre billeteras del mismo usuario. No cuentan como ingreso ni gasto,
-- así que no afectan a presupuestos.
CREATE TABLE traspasos (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id              BIGINT        NOT NULL REFERENCES usuarios (id),
    billetera_origen_id     BIGINT        NOT NULL REFERENCES billeteras (id),
    billetera_destino_id    BIGINT        NOT NULL REFERENCES billeteras (id),
    monto                   NUMERIC(12,2) NOT NULL,
    descripcion             VARCHAR(255),
    fecha                   DATE          NOT NULL,
    CONSTRAINT ck_traspaso_distinto CHECK (billetera_origen_id <> billetera_destino_id)
);
